export const CLUBS: Club[] = ROWS.map(([id, name, leagueId, strength]) => ({
  id,
  name,
  leagueId,
  strength,
}))

export function clubById(id: string): Club | undefined {
  return CLUBS.find((club) => club.id === id)
}

export function clubsInLeague(leagueId: string): Club[] {
  return CLUBS.filter((club) => club.leagueId === leagueId)
}

export function leagueOf(club: Club): League {
  const league = leagueById(club.leagueId)

  if (!league) {
    throw new Error(`Clube ${club.id} aponta para liga inexistente: ${club.leagueId}`)
  }

  return league
}

export function clubsByCountry(country: string): Club[] {
  return CLUBS.filter((club) => leagueOf(club).country === country)
}

/** Clubes numa faixa de forca — sorteia clube inicial e gera propostas. */
export function clubsInStrengthRange(min: number, max: number): Club[] {
  return CLUBS.filter((club) => club.strength >= min && club.strength <= max)
}
